interface TemplateInput {
  id: string;
  name: string;
  tagline: string;
  category: TemplateCategory;
  archetype: Archetype;
  industry: string;
  level: ExperienceLevel;
  style: TemplateStyle;
  atsScore: number;
  columns?: 1 | 2 | 3;
  pageSize?: PageSettings["size"];
  sidebarWidth?: number;
  sidebarPosition?: "left" | "right";
  headerLayout?: LayoutConfig["headerLayout"];
  order: SectionKind[];
  side?: SectionKind[];
  theme: TemplateThemeInput;
  tags: string[];
}

const atsLabel = (score: number): string => {
  if (score >= 92) return "ATS-safe — single column, standard headings";
  if (score >= 84) return "ATS-safe — simple structure, minor styling";
  if (score >= 70) return "Mostly ATS-safe — two columns, test before submitting";
  return "Not ATS-safe — visual layout, best for direct or portfolio applications";
};

const buildTheme = (input: TemplateThemeInput): ThemeConfig => {
  const base = defaultTheme();
  return {
    ...base,
    fontFamily: input.font,
    headingFontFamily: input.headingFont ?? input.font,
    accentColor: input.accent,
    mutedColor: input.muted ?? "#6b7280",
    bandColor: input.band ?? input.accent,
    bandTextColor: input.bandText ?? "#ffffff",
    headingStyle: input.headingStyle ?? "rule",
    headingCase: input.headingCase ?? "upper",
    divider: input.divider ?? "thin",
    density: input.density ?? "normal",
    headerAlign: input.headerAlign ?? "left",
    fontScale: input.fontScale ?? 1,
    headingSize: input.headingSize ?? 10.5,
    nameSize: input.nameSize ?? 26,
    lineHeight: input.lineHeight ?? 1.42,
    sectionSpacing: input.sectionSpacing ?? 14,
    bulletStyle: input.bulletStyle ?? "disc",
    showIcons: input.showIcons ?? true,
  };
};

const define = (input: TemplateInput): ResumeTemplate => {
  const arch = archetypeOf(input.archetype);
  const columns = input.columns ?? 1;
  const pageSize = input.pageSize ?? "a4";
  const layout: LayoutConfig = {
    columns,
    sidebarWidth: input.sidebarWidth ?? 32,
    sidebarPosition: input.sidebarPosition ?? "right",
    headerLayout: input.headerLayout ?? (arch.bandHeader ? "band" : arch.monogram ? "monogram" : "stacked"),
    allowColumns: true,
  };
  const theme = buildTheme({
    ...input.theme,
    headingStyle: input.theme.headingStyle ?? arch.headingStyle,
  });
  return {
    id: input.id,
    name: input.name,
    tagline: input.tagline,
    category: input.category,
    archetype: input.archetype,
    industry: input.industry,
    level: input.level,
    style: input.style,
    atsScore: input.atsScore,
    atsLabel: atsLabel(input.atsScore),
    columns,
    pageSize,
    theme,
    layout,
    sectionOrder: input.order,
    sidebarKinds: columns > 1 ? input.side ?? SIDE.core : [],
    tags: input.tags,
  };
};

