/**
 * Reorder + re-column an existing document for a template. Content objects are
 * reused by reference, so switching templates can never drop user data.
 */
export const applyTemplateToSections = (
  document: ResumeDocument,
  template: ResumeTemplate,
): ResumeDocument["sections"] => {
  const rank = new Map(template.sectionOrder.map((kind, i) => [kind, i]));
  const orderFallback = template.sectionOrder.length;
  const sideSet = new Set(template.sidebarKinds);

  const indexed = document.sections.map((section, index) => ({ section, index }));
  indexed.sort((a, b) => {
    const ra = rank.get(a.section.kind) ?? orderFallback + a.index;
    const rb = rank.get(b.section.kind) ?? orderFallback + b.index;
    if (ra === rb) return a.index - b.index;
    return ra - rb;
  });

  return indexed.map(({ section }) => {
    let column: 0 | 1 | 2 = 0;
    if (template.columns === 1) {
      column = 0;
    } else if (template.columns === 3) {
      column = section.column;
    } else {
      column = sideSet.has(section.kind) ? 1 : 0;
    }
    return { ...section, column };
  }) as ResumeDocument["sections"];
};

