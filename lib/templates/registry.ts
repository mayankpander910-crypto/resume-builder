export const filterTemplates = (filters: TemplateFilters): ResumeTemplate[] => {
  const q = filters.search?.trim().toLowerCase();
  return GALLERY_TEMPLATES.filter((t) => {
    if (filters.category && filters.category !== "all" && t.category !== filters.category) return false;
    if (filters.industry && filters.industry !== "all" && t.industry !== filters.industry) return false;
    if (filters.level && filters.level !== "all" && t.level !== filters.level && t.level !== "any") return false;
    if (filters.atsOnly && t.atsScore < 90) return false;
    if (filters.columns && filters.columns !== "all" && t.columns !== filters.columns) return false;
    if (filters.style && filters.style !== "all" && t.style !== filters.style) return false;
    if (q) {
      const haystack = `${t.name} ${t.tagline} ${t.industry} ${t.category} ${t.style} ${t.tags.join(" ")}`.toLowerCase();
      if (!haystack.includes(q)) return false;
    }
    return true;
  });
};

